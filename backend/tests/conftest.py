@pytest_asyncio.fixture()
async def test_engine():
    """Create a fresh async engine pointing at the test database.

    Creates all ORM tables before yielding and drops them on teardown.
    Requires ``pkbe_test`` to exist (DDL is handled here, not the DB itself).
    """
    engine = create_async_engine(TEST_DB_URL, echo=False, pool_pre_ping=True)
    async with engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)
    yield engine
    async with engine.begin() as conn:
        await conn.run_sync(Base.metadata.drop_all)
    await engine.dispose()


@pytest_asyncio.fixture()
async def patched_db(test_engine):
    """Patch the global database session factories to point at the test engine.

    Also overrides FastAPI's get_db dependency so every in-process API call
    uses the same test database.  Yields an open AsyncSession for direct DB
    manipulation in tests (e.g. seeding data, reading audit_logs).

    Restores all patched values on teardown.
    """
    TestSessionLocal = async_sessionmaker(
        bind=test_engine,
        class_=AsyncSession,
        expire_on_commit=False,
    )

    # Capture originals so we can restore them after the test
    orig_db_engine = database.engine
    orig_db_session = database.AsyncSessionLocal
    orig_dep_session = dependencies.AsyncSessionLocal

    # Patch module-level globals (audit_logger reads dependencies.AsyncSessionLocal
    # directly, so that import must be patched too)
    database.engine = test_engine
    database.AsyncSessionLocal = TestSessionLocal
    dependencies.AsyncSessionLocal = TestSessionLocal

    # Override the FastAPI get_db dependency
    async def _override_get_db():
        async with TestSessionLocal() as session:
            yield session

    app.dependency_overrides[get_db] = _override_get_db

    async with TestSessionLocal() as session:
        yield session

    # Restore
    app.dependency_overrides.pop(get_db, None)
    database.engine = orig_db_engine
    database.AsyncSessionLocal = orig_db_session
    dependencies.AsyncSessionLocal = orig_dep_session


