@pytest.fixture()
def mock_anthropic(mocker):
    """Patch anthropic.AsyncAnthropic so no real Anthropic calls are made.

    - Calls that include a ``tools`` kwarg (PK extraction) return a tool_use block
      with one valid Cmax parameter sourced from PMID 23456789.
    - All other calls (section generation) return a text block with placeholder text.

    The fixture returns the underlying AsyncMock so tests can inspect call_count etc.
    """

    def _tool_response() -> MagicMock:
        param_block = MagicMock()
        param_block.type = "tool_use"
        param_block.name = "record_pk_parameters"
        param_block.input = {
            "parameters": [
                {
                    "parameter": "Cmax",
                    "value": 1.03,
                    "unit": "µg/mL",
                    "source_pmid": "23456789",
                    "population": "healthy adults",
                    "confidence": 0.89,
                },
                {
                    "parameter": "t_half",
                    "value": 6.2,
                    "unit": "h",
                    "source_pmid": "23456789",
                    "population": "healthy adults",
                    "confidence": 0.93,
                },
                # This one has an invalid PMID — must be filtered out by _validate_pmids
                {
                    "parameter": "bioavailability",
                    "value": 55.0,
                    "unit": "%",
                    "source_pmid": "99999999",  # not in PubMed results → filtered
                    "population": "healthy adults",
                    "confidence": 0.85,
                },
            ]
        }
        resp = MagicMock()
        resp.content = [param_block]
        return resp

    def _text_response(text: str = MOCK_SECTION_TEXT) -> MagicMock:
        block = MagicMock()
        block.type = "text"
        block.text = text
        resp = MagicMock()
        resp.content = [block]
        return resp

    async def _side_effect(*args, **kwargs):
        if kwargs.get("tools"):
            return _tool_response()
        return _text_response()

    mock_messages = AsyncMock(side_effect=_side_effect)
    mock_client = MagicMock()
    mock_client.messages.create = mock_messages

    mocker.patch("anthropic.AsyncAnthropic", return_value=mock_client)
    return mock_client


