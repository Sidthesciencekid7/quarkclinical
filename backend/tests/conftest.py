def register_pubmed_mocks(httpx_mock) -> None:
    """Add the two PubMed E-utilities responses to an httpx_mock fixture.

    Registered:
      1. esearch.fcgi  → JSON list of PMIDs
      2. efetch.fcgi   → PubMed XML with two metformin abstracts
    """
    httpx_mock.add_response(
        method="GET",
        url=re.compile(
            r"^https://eutils\.ncbi\.nlm\.nih\.gov/entrez/eutils/esearch\.fcgi(\?.*)?$"
        ),
        json={
            "esearchresult": {
                "idlist": PUBMED_ESEARCH_PMIDS,
                "count": str(len(PUBMED_ESEARCH_PMIDS)),
                "retmax": "20",
            }
        },
    )
    httpx_mock.add_response(
        method="GET",
        url=re.compile(
            r"^https://eutils\.ncbi\.nlm\.nih\.gov/entrez/eutils/efetch\.fcgi(\?.*)?$"
        ),
        text=PUBMED_EFETCH_XML,
        headers={"Content-Type": "application/xml; charset=utf-8"},
    )
    # create_protocol() always calls fetch_dailymed() too (independent of
    # MOCK_AI, which only gates the AI-generation stage) — an empty result set
    # makes _dailymed_search() return [] and fetch_dailymed() gracefully return
    # None, matching the sparse-literature degrade path already verified for
    # real drugs (see project_stress_test_findings memory).
    httpx_mock.add_response(
        method="GET",
        url=re.compile(r"^https://dailymed\.nlm\.nih\.gov/dailymed/services/v2/spls\.json(\?.*)?$"),
        json={"data": []},
    )
